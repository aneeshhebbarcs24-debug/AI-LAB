def is_variable(x):
    return isinstance(x, str) and x.startswith("?")


def substitute(atom, theta):
    return tuple(theta.get(x, x) if is_variable(x) else x
                 for x in atom)


def unify(x, y, theta=None):
    if theta is None:
        theta = {}

    x = substitute(x, theta)
    y = substitute(y, theta)

    if x == y:
        return theta

    if len(x) != len(y):
        return None

    for a, b in zip(x, y):
        if a == b:
            continue
        elif is_variable(a):
            theta[a] = b
        elif is_variable(b):
            theta[b] = a
        else:
            return None

    return theta


def match(premises, facts, theta=None):
    if theta is None:
        theta = {}

    if not premises:
        yield theta
        return

    first = substitute(premises[0], theta)

    for fact in facts:
        new_theta = unify(first, fact, theta.copy())

        if new_theta is not None:
            yield from match(premises[1:], facts, new_theta)


def forward_chaining(KB, rules, query):
    facts = list(KB)
    derived = []
    proof = {}

    while True:
        new = []

        for i, (premises, conclusion) in enumerate(rules, 1):
            for theta in match(premises, facts):
                q = substitute(conclusion, theta)

                if q not in facts and q not in new:
                    new.append(q)
                    proof[q] = (i, [substitute(p, theta)
                                    for p in premises])

        if not new:
            break

        facts.extend(new)
        derived.extend(new)

        if query in facts:
            break

    return derived, proof, query in facts


