def parse_literal(literal):
    neg = literal.startswith("!")
    literal = literal[1:] if neg else literal
    pred, args = literal.split("(")
    args = args[:-1].split(",")
    return neg, pred, args


def is_variable(term):
    return term in {"x", "y", "z"}


def substitute(term, subs):
    while term in subs:
        term = subs[term]
    return term


def unify(a, b, subs):
    a = substitute(a, subs)
    b = substitute(b, subs)

    if a == b:
        return subs

    if is_variable(a):
        subs[a] = b
        return subs

    if is_variable(b):
        subs[b] = a
        return subs

    return None


def apply_substitution(literal, subs):
    neg, pred, args = parse_literal(literal)
    args = [substitute(a, subs) for a in args]
    return ("!" if neg else "") + pred + "(" + ",".join(args) + ")"


def resolve(c1, c2):
    for l1 in c1:
        for l2 in c2:
            n1, p1, a1 = parse_literal(l1)
            n2, p2, a2 = parse_literal(l2)

            if p1 == p2 and n1 != n2 and len(a1) == len(a2):
                subs = {}

                for a, b in zip(a1, a2):
                    subs = unify(a, b, subs)
                    if subs is None:
                        break

                if subs is not None:
                    resolvent = []

                    for lit in c1:
                        if lit != l1:
                            resolvent.append(apply_substitution(lit, subs))

                    for lit in c2:
                        if lit != l2:
                            resolvent.append(apply_substitution(lit, subs))

                    return resolvent

    return None


